// Continuous real browser capture of the standalone synthetic demo, not a live model.
// Run from this repository after npm ci and starting npm run dev on port 4173.
import {chromium,expect} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
const root=process.cwd();
const out=resolve(root,'showcase-video');
await mkdir(out,{recursive:true});
const fixture=JSON.parse(await readFile(resolve(root,'demo/validation-fixture.json'),'utf8'));
const packageInfo=JSON.parse(await readFile(resolve(root,'package.json'),'utf8'));
const browser=await chromium.launch({channel:'chrome',headless:true,chromiumSandbox:true});
let context;
const started=new Date().toISOString();
const steps=[];
try {
 context=await browser.newContext({viewport:{width:1280,height:900},serviceWorkers:'block',recordVideo:{dir:out,size:{width:1280,height:900}}});
 context.setDefaultTimeout(10000);
 const errors=[];
 const blocked=[];
 await context.route('**/*',route=>{
  const url=new URL(route.request().url());
  if(url.origin==='http://127.0.0.1:4173')return route.continue();
  blocked.push(url.origin);return route.abort();
 });
 await context.routeWebSocket('**/*',socket=>{if(new URL(socket.url()).origin==='ws://127.0.0.1:4173'){socket.connectToServer();return;}blocked.push('external-websocket');socket.close();});
 const page=await context.newPage();
 page.on('pageerror',error=>errors.push(error.message));
 const pause=async name=>{steps.push({name,at:new Date().toISOString()});await page.waitForTimeout(2200);};
 await page.goto('http://127.0.0.1:4173');
 await pause('Standalone synthetic preview; no live model or external service');
 await page.getByRole('button',{name:'Stream validation example',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Validated.'}).waitFor();
 const input=page.getByRole('textbox',{name:'Synthetic code',exact:true});
 const preview=page.getByRole('button',{name:'Preview valid code',exact:true});
 await expect(input).toHaveValue('AB12');await pause('Initial AB12');
 await input.fill('bad');
 await page.getByText('Use two uppercase letters followed by two digits',{exact:true}).waitFor();
 await expect(preview).toBeDisabled();await pause('Invalid input visibly blocked');
 await input.fill('CD34');await expect(preview).toBeEnabled();
 await preview.click();await pause('Valid action logged locally');
 await page.getByRole('button',{name:'Export recording',exact:true}).click();
 await page.getByText('Portable recording: inspect, paste, restore',{exact:true}).click();
 const editor=page.getByRole('textbox',{name:'Portable recording',exact:true});
 const saved=await editor.inputValue();const parsed=JSON.parse(saved);
 assert.equal(parsed.actions.length,1);assert.deepEqual(parsed.actions[0].action.context,{code:'CD34'});
 await pause('Explicit export, not automatic persistence');
 await page.reload();await expect(page.getByRole('status')).toHaveText('Ready');await expect(input).toHaveCount(0);await expect(page.locator('pre')).toHaveText('No actions sent.');await pause('Actual reload clears in-memory state');
 await page.getByText('Portable recording: inspect, paste, restore',{exact:true}).click();
 await expect(editor).toHaveValue('');await editor.fill(saved);await pause('Explicit paste of synthetic recording');
 await page.getByRole('button',{name:'Restore recording',exact:true}).click();
 await expect(input).toHaveValue('CD34');await expect(preview).toBeEnabled();await expect(page.getByRole('status')).toContainText('1 historical actions NOT sent.');await expect(page.locator('pre')).toHaveText('No actions sent.');
 await page.getByText('Portable recording: inspect, paste, restore',{exact:true}).click();
 await pause('Restored value without resending historical action');
 await page.getByRole('button',{name:'Stream synthetic example',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Validated.'}).waitFor();
 const messages=structuredClone(fixture);
 messages[2].updateComponents.components.find(c=>c.id==='code').validationRegexp='';
 await page.getByText('Portable recording: inspect, paste, restore',{exact:true}).click();
 await editor.fill(JSON.stringify({format:'dsh-a2ui-recording/1',messages,snapshots:[],actions:[]}));
 await page.getByRole('button',{name:'Restore recording',exact:true}).click();
 await page.getByRole('status').filter({hasText:'COMPATIBILITY: TextField.validationRegexp'}).waitFor();
 await expect(input).toHaveCount(0);
 await expect(page.getByRole('textbox',{name:'Workshop topic',exact:true})).toHaveValue('Ceramics for beginners');
 await expect(page.locator('pre')).toHaveText('No actions sent.');
 await page.getByText('Portable recording: inspect, paste, restore',{exact:true}).click();
 await pause('Unsupported property rejected, previous surface preserved');
 assert.deepEqual(errors,[]);assert.deepEqual(blocked,[]);
 const video=page.video();await context.close();context=undefined;
 assert.ok(video);await video.saveAs(resolve(out,'dsh-a2ui-synthetic-demo.webm'));
 const sourceCommit=/^[a-f0-9]{40}$/.test(process.env.GITHUB_SHA||'')?process.env.GITHUB_SHA:null;
 const videoSha256=createHash('sha256').update(await readFile(resolve(out,'dsh-a2ui-synthetic-demo.webm'))).digest('hex');
 await writeFile(resolve(out,'receipt.json'),JSON.stringify({sourceCommit,videoSha256,version:packageInfo.version,started,finished:new Date().toISOString(),steps,synthetic:true,liveModel:false,fullHost:false,automaticPersistence:false,errors,blocked},null,2)+'\n');
} finally {try{if(context)await context.close();}finally{await browser.close();}}
